def main() -> None:
    set_global_seed(CFG.master_seed)

    print("TensorFlow version:", tf.__version__)
    print("Keras version:", getattr(tf.keras, "__version__", "unknown"))
    print("Eager execution:", tf.executing_eagerly())

    max_episodes = 20 if CFG.quick_test else CFG.max_episodes
    max_episode_steps = 20 if CFG.quick_test else CFG.max_episode_steps
    warmup_steps = 100 if CFG.quick_test else CFG.warmup_steps

    original_state_dim = 4 + 2 * CFG.num_agents
    global_state_dim = 2 * original_state_dim
    local_observation_dim = 12

    data_dir = Path("data")
    data_dir.mkdir(parents=True, exist_ok=True)

    trajectory_path = data_dir / (
        f"fixed_env_trajectory_seed{CFG.environment_seed}_"
        f"ep{max_episodes}_steps{max_episode_steps}_K{CFG.num_agents}.npz"
    )
    trajectories = FixedTrajectoryBank(
        str(trajectory_path),
        max_episodes,
        max_episode_steps,
        CFG.num_agents,
        CFG.environment_seed,
    )

    maddpg = MADDPG(
        original_state_dim,
        global_state_dim,
        local_observation_dim,
        CFG,
    )

    total_training_steps = max_episodes * max_episode_steps
    ou_noise = OrnsteinUhlenbeckNoise(
        CFG.num_agents,
        CFG.action_dim_per_agent,
        CFG.ou_theta,
        CFG.ou_sigma_start,
        CFG.ou_sigma_end,
        CFG.ou_dt,
        total_training_steps,
        CFG.exploration_seed,
    )
    warmup_rng = np.random.RandomState(CFG.exploration_seed + 1)

    start_time = time.time()
    global_step = 0

    episode_rewards = []
    episode_fairness_last = []
    episode_energy_last = []
    episode_fairness_mean = []
    episode_energy_mean = []
    episode_effective_action_mean = []
    episode_joint_action_std_mean = []

    actor_loss_means = []
    critic_loss_means = []
    per_agent_actor_losses = []
    per_agent_critic_losses = []

    for episode in range(max_episodes):
        user_positions, other_state = trajectories.reset(episode)
        current_original_state = np.concatenate(
            [other_state.flatten(), user_positions.flatten()]
        ).astype(np.float32)
        previous_original_state = np.zeros_like(current_original_state)
        global_state = np.concatenate(
            [current_original_state, previous_original_state]
        ).astype(np.float32)

        ou_noise.reset()
        episode_reward = 0.0
        fairness_values = []
        energy_values = []
        effective_action_values = []
        joint_action_std_values = []
        latest_losses = None

        for step in range(max_episode_steps):
            if global_step < warmup_steps:
                joint_actions = warmup_rng.uniform(
                    0.0,
                    CFG.action_bound,
                    size=(CFG.num_agents, CFG.action_dim_per_agent),
                ).astype(np.float32)
            else:
                exploration = ou_noise.sample(global_step)
                joint_actions = maddpg.choose_actions(
                    global_state,
                    exploration_noise=exploration,
                )

            scalar_action = effective_scalar_action(joint_actions)

            user_delta, other_delta = trajectories.step_delta(episode, step)
            user_positions = user_positions + user_delta
            other_state = other_state + other_delta

            next_original_state = np.concatenate(
                [other_state.flatten(), user_positions.flatten()]
            ).astype(np.float32)
            next_global_state = np.concatenate(
                [next_original_state, current_original_state]
            ).astype(np.float32)

            distances = np.sqrt(np.sum(user_positions ** 2, axis=1))
            channel_gains = 1.0 / (1.0 + distances)
            reward = reward_function(channel_gains, scalar_action, CFG.energy_weight)
            fairness = jain_fairness_index(channel_gains)
            energy = energy_consumption(scalar_action)
            done = step == max_episode_steps - 1

            maddpg.store_transition(
                global_state,
                joint_actions,
                reward,
                next_global_state,
                done,
            )

            if (
                maddpg.memory.size >= max(warmup_steps, CFG.batch_size)
                and global_step % CFG.update_every == 0
            ):
                latest_losses = maddpg.learn()
                actor_loss_means.append(latest_losses["actor_loss_mean"])
                critic_loss_means.append(latest_losses["critic_loss_mean"])
                per_agent_actor_losses.append(latest_losses["actor_losses"])
                per_agent_critic_losses.append(latest_losses["critic_losses"])

            episode_reward += reward
            fairness_values.append(fairness)
            energy_values.append(energy)
            effective_action_values.append(scalar_action)
            joint_action_std_values.append(float(np.std(joint_actions)))

            current_original_state = next_original_state.copy()
            global_state = next_global_state.copy()
            global_step += 1

        episode_rewards.append(float(episode_reward))
        episode_fairness_last.append(float(fairness_values[-1]))
        episode_energy_last.append(float(energy_values[-1]))
        episode_fairness_mean.append(float(np.mean(fairness_values)))
        episode_energy_mean.append(float(np.mean(energy_values)))
        episode_effective_action_mean.append(float(np.mean(effective_action_values)))
        episode_joint_action_std_mean.append(float(np.mean(joint_action_std_values)))

        if latest_losses is None:
            loss_text = "warming up"
        else:
            loss_text = (
                f"actor_mean={latest_losses['actor_loss_mean']:.4f}, "
                f"critic_mean={latest_losses['critic_loss_mean']:.4f}, "
                f"OU_sigma={ou_noise.current_sigma(global_step):.4f}"
            )

        print(
            f"Episode {episode + 1:4d}/{max_episodes} | "
            f"Reward={episode_reward:10.4f} | "
            f"Fairness(last)={fairness_values[-1]:.4f} | "
            f"Energy(last)={energy_values[-1]:.4f} | "
            f"EffectiveAction(mean)={np.mean(effective_action_values):.4f} | "
            f"{loss_text}"
        )

        if (episode + 1) % CFG.checkpoint_interval == 0:
            elapsed = time.time() - start_time
            checkpoint_path = data_dir / (
                f"maddpg_checkpoint_seed{CFG.master_seed}_ep{episode + 1}.npz"
            )
            save_results(
                str(checkpoint_path),
                episode + 1,
                episode_rewards,
                episode_fairness_last,
                episode_energy_last,
                episode_fairness_mean,
                episode_energy_mean,
                episode_effective_action_mean,
                episode_joint_action_std_mean,
                actor_loss_means,
                critic_loss_means,
                per_agent_actor_losses,
                per_agent_critic_losses,
                elapsed,
                str(trajectory_path),
            )
            print("Checkpoint saved:", checkpoint_path)

    running_time = time.time() - start_time
    print(f"Running time: {running_time:.2f} seconds")

    final_path = data_dir / f"data_maddpg_keras3_seed{CFG.master_seed}.npz"
    save_results(
        str(final_path),
        max_episodes,
        episode_rewards,
        episode_fairness_last,
        episode_energy_last,
        episode_fairness_mean,
        episode_energy_mean,
        episode_effective_action_mean,
        episode_joint_action_std_mean,
        actor_loss_means,
        critic_loss_means,
        per_agent_actor_losses,
        per_agent_critic_losses,
        running_time,
        str(trajectory_path),
    )
    print("Saved final results to:", final_path)

    plt.figure(figsize=(12, 5))
    plt.subplot(1, 2, 1)
    plt.plot(episode_rewards, label="MADDPG reward")
    plt.xlabel("Episode")
    plt.ylabel("Episodic Reward")
    plt.legend()

    plt.subplot(1, 2, 2)
    plt.plot(episode_fairness_mean, label="Mean fairness")
    plt.xlabel("Episode")
    plt.ylabel("Jain Fairness Index")
    plt.legend()
    plt.tight_layout()
    plt.show()

    plt.figure(figsize=(12, 5))
    plt.subplot(1, 2, 1)
    plt.plot(episode_energy_mean, label="Mean energy consumption")
    plt.xlabel("Episode")
    plt.ylabel("Energy")
    plt.legend()

    plt.subplot(1, 2, 2)
    plt.plot(episode_effective_action_mean, label="Mean effective action")
    plt.xlabel("Episode")
    plt.ylabel("Action")
    plt.legend()
    plt.tight_layout()
    plt.show()


